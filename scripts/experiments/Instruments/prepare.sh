#!/usr/bin/env bash
set -eo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../../.." && pwd)"

GENREC_ROOT="${GENREC_ROOT:-${REPO_ROOT}}"
DATA_ROOT="${DATA_ROOT:-${REPO_ROOT}/data}"
CATEGORY="${CATEGORY:-Instruments}"
INDEX_PATH="${INDEX_PATH:-${DATA_ROOT}/${CATEGORY}/${CATEGORY}.index.json}"
DATA_VARIANT="${DATA_VARIANT:-Instruments_grec_index}"
DATASET_SUBDIR="${DATASET_SUBDIR:-Instruments_grec_index}"
DATASET_KEY_PREFIX="${DATASET_KEY_PREFIX:-Instruments_grec_index}"
OUTPUT_DIR="${OUTPUT_DIR:-${GENREC_ROOT}/data/Instruments_grec_index}"
SEQ_SAMPLE="${SEQ_SAMPLE:-10000}"
TASK3_SAMPLE="${TASK3_SAMPLE:-20000}"
HISTORY_MAX="${HISTORY_MAX:-50}"
TRAIN_ROW_ORDER="${TRAIN_ROW_ORDER:-reverse}"
SPLIT_STRATEGY="${SPLIT_STRATEGY:-grec}"

PREPARE_ENV=(
  REPO_ROOT="$REPO_ROOT"
  GENREC_ROOT="$GENREC_ROOT"
  DATA_ROOT="$DATA_ROOT"
  CATEGORY="$CATEGORY"
  INDEX_PATH="$INDEX_PATH"
  DATA_VARIANT="$DATA_VARIANT"
  DATASET_SUBDIR="$DATASET_SUBDIR"
  DATASET_KEY_PREFIX="$DATASET_KEY_PREFIX"
  OUTPUT_DIR="$OUTPUT_DIR"
  SEQ_SAMPLE="$SEQ_SAMPLE"
  TASK3_SAMPLE="$TASK3_SAMPLE"
  HISTORY_MAX="$HISTORY_MAX"
  TRAIN_ROW_ORDER="$TRAIN_ROW_ORDER"
  SPLIT_STRATEGY="$SPLIT_STRATEGY"
)

exec env "${PREPARE_ENV[@]}" \
  bash "${REPO_ROOT}/scripts/experiments/Instruments/prepare_instruments_grec_sft_fixed_hint_data.sh" \
  "$@"
